//! `xtask gen-dto`: the JSON Schemas of the engine API's types and the C# glue that reads them
//! (M3_DESIGN.md §6.5, package M3-GEN-DTO; fallback of design 15).
//!
//! The schemas come from `purge-rpc` (`schemars::JsonSchema`) and are written to
//! `ui/Purge.Client/Schema/`. The C# *models* are hand-written (`ui/Purge.Client/Rpc/RpcModels.cs`); this
//! command generates the `System.Text.Json` source-generation context for them and the fixture registry
//! the C# round-trip test walks. NJsonSchema's output was tried and rejected: it turns every
//! discriminated union into an empty class with untyped `[JsonExtensionData]` members, which is neither
//! faithful nor AOT-clean (design 15's fallback).
//!
//! Everything written here is committed; `--check` writes nothing and fails if a file on disk differs.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

/// The directory of the generated schemas, under the client project.
const SCHEMA_DIR: &str = "ui/Purge.Client/Schema";
/// The directory of the generated C# glue.
const GENERATED_DIR: &str = "ui/Purge.Client/Generated";

pub fn run(root: &Path, args: &[String]) -> Result<bool> {
    let mut check = false;
    for arg in args {
        match arg.as_str() {
            "--check" => check = true,
            other => bail!("gen-dto: unknown argument {other}"),
        }
    }

    let schemas = purge_rpc::methods::schemas();
    let names: BTreeSet<String> = schemas.iter().map(|s| s.name.clone()).collect();
    let fixtures = purge_rpc::methods::dtos();
    let fixture_stems: BTreeSet<String> = fixtures.iter().map(|d| d.stem.clone()).collect();
    if fixture_stems.len() != fixtures.len() {
        bail!("gen-dto: a fixture stem is used twice");
    }

    let mut outputs: Vec<(PathBuf, String)> = Vec::new();
    for export in &schemas {
        let text = serde_json::to_string_pretty(&export.schema)
            .with_context(|| format!("serialising the schema of {}", export.name))?
            + "\n";
        outputs.push((
            root.join(SCHEMA_DIR).join(format!("{}.json", export.name)),
            text,
        ));
    }
    outputs.push((
        root.join(GENERATED_DIR).join("RpcJsonContext.g.cs"),
        render_context(&names),
    ));
    outputs.push((
        root.join(GENERATED_DIR).join("RpcFixtures.g.cs"),
        render_fixtures(&fixtures),
    ));

    if check {
        let mut stale: Vec<PathBuf> = Vec::new();
        for (path, text) in &outputs {
            match std::fs::read_to_string(path) {
                Ok(disk) if disk == *text => {}
                _ => stale.push(path.clone()),
            }
        }
        for (dir, extension) in [(SCHEMA_DIR, "json"), (GENERATED_DIR, "cs")] {
            let expected: BTreeSet<PathBuf> = outputs
                .iter()
                .map(|(path, _)| path.clone())
                .filter(|path| path.extension().is_some_and(|e| e == extension))
                .collect();
            for entry in std::fs::read_dir(root.join(dir))? {
                let path = entry?.path();
                if path.extension().is_some_and(|e| e == extension) && !expected.contains(&path) {
                    stale.push(path);
                }
            }
        }
        if stale.is_empty() {
            return Ok(true);
        }
        stale.sort();
        for path in &stale {
            eprintln!("gen-dto: stale: {}", path.display());
        }
        bail!(
            "{} generated file(s) differ; run `cargo xtask gen-dto`",
            stale.len()
        );
    }

    for dir in [SCHEMA_DIR, GENERATED_DIR] {
        let dir = root.join(dir);
        if dir.exists() {
            std::fs::remove_dir_all(&dir).with_context(|| format!("clearing {}", dir.display()))?;
        }
        std::fs::create_dir_all(&dir)?;
    }
    for (path, text) in &outputs {
        std::fs::write(path, text).with_context(|| format!("writing {}", path.display()))?;
    }
    println!(
        "gen-dto: {} schema(s), {} fixture(s)",
        schemas.len(),
        fixtures.len()
    );
    Ok(true)
}

/// The source-generation context: one `JsonSerializable` per type, so Native AOT has no reflection.
fn render_context(names: &BTreeSet<String>) -> String {
    let mut out = String::new();
    out.push_str(
        "// <auto-generated> by `cargo xtask gen-dto` from crates/purge-rpc. Do not edit.\n\
         \n\
         using System.Text.Json.Serialization;\n\
         \n\
         namespace Purge.Client.Rpc;\n\
         \n\
         [JsonSourceGenerationOptions(WriteIndented = false)]\n",
    );
    for name in names {
        out.push_str(&format!("[JsonSerializable(typeof({name}))]\n"));
    }
    out.push_str("internal partial class RpcJsonContext : JsonSerializerContext\n{\n}\n");
    out
}

/// The fixture registry: every stem and the reader/writer of its type, for `FixtureRoundTrip`.
fn render_fixtures(fixtures: &[purge_rpc::methods::Dto]) -> String {
    let mut out = String::new();
    out.push_str(
        "// <auto-generated> by `cargo xtask gen-dto` from crates/purge-rpc. Do not edit.\n\
         \n\
         namespace Purge.Client.Rpc;\n\
         \n\
         /// <summary>Every fixture of the engine API, read and written as its Rust type mirrors.</summary>\n\
         public static class RpcFixtures\n\
         {\n\
         \x20   /// <summary>The fixture stem and a function that reads it and writes it back.</summary>\n\
         \x20   public static readonly (string Stem, Func<string, string> RoundTrip)[] All =\n\
         \x20   [\n",
    );
    let mut ordered: Vec<_> = fixtures.iter().collect();
    ordered.sort_by(|a, b| a.stem.cmp(&b.stem));
    for dto in ordered {
        out.push_str(&format!(
            "        (\"{}\", json => RpcJson.RoundTrip(json, RpcJsonContext.Default.{})),\n",
            dto.stem, dto.type_name
        ));
    }
    out.push_str("    ];\n}\n");
    out
}
