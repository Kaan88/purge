//! The quiet uninstall command of an inventory entry (ENGINE_PLAN.md §4.4 "Quiet commands").
//!
//! Rules, in order:
//!
//! 1. `QuietUninstallString` when the key has one, as written ([`QuietCommand::generated`] = false). One
//!    exception: the value Inno Setup writes by itself is `"<uninstaller>" /SILENT`, which still shows a
//!    progress window and can stop on message boxes; for an Inno entry whose quiet string runs the same
//!    uninstaller with nothing but Inno's own silence switches, the full form of rule 2 is generated.
//! 2. Otherwise a generated command, by installer kind:
//!    - **MSI**: `msiexec.exe /x {ProductCode} /qn REBOOT=ReallySuppress`, built from the ProductCode, never
//!      from the `UninstallString`, so `MsiExec.exe /I{…}` (maintenance mode, any spacing) becomes `/x`.
//!      The executable is `%SystemRoot%\System32\msiexec.exe`, unexpanded like every path read from the
//!      registry ([`QuietCommand::expand`] resolves it), so it is never looked up through the search path.
//!    - **Inno Setup**: the uninstaller with `/VERYSILENT /SUPPRESSMSGBOXES /NORESTART` (any `/SILENT`
//!      dropped, existing switches kept once).
//!    - **NSIS**: the uninstaller with `/S` (case-sensitive, as NSIS requires). NSIS takes `_?=<dir>` only as
//!      the last parameter and reads everything after it as the directory, so `/S` goes before it.
//!    - **Burn**: the bundle with `/uninstall /quiet /norestart` (WiX Burn's documented switches).
//!    - **Unknown**: no quiet form ([`QuietError::NoQuietForm`]).
//!
//! Splitting a command into executable and arguments uses `purge_win::cmdline` (BCU `ProcessStartCommand`).

use std::collections::BTreeMap;

use purge_model::{InstallerKind, InventoryEntry};
use purge_win::cmdline::{self, CmdlineError};
use purge_win::env::{EnvMap, expand_with};
use serde::{Deserialize, Serialize};

use crate::kind::{nsis_instdir_pos, uninstaller};

/// The executable of a generated MSI command, unexpanded.
pub const MSIEXEC: &str = r"%SystemRoot%\System32\msiexec.exe";

/// The arguments of a generated MSI command after the ProductCode.
pub const MSI_QUIET_ARGS: &str = "/qn REBOOT=ReallySuppress";

/// The switches added to an Inno Setup uninstaller.
pub const INNO_QUIET_SWITCHES: [&str; 3] = ["/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART"];

/// The switch added to an NSIS uninstaller (NSIS switches are case-sensitive).
pub const NSIS_QUIET_SWITCH: &str = "/S";

/// The switches added to a Burn bundle.
pub const BURN_QUIET_SWITCHES: [&str; 3] = ["/uninstall", "/quiet", "/norestart"];

/// Inno Setup's own uninstaller switches that only control how quiet it is.
const INNO_SILENCE_SWITCHES: [&str; 4] =
    ["/SILENT", "/VERYSILENT", "/SUPPRESSMSGBOXES", "/NORESTART"];

/// A command that uninstalls an entry without user interaction.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct QuietCommand {
    /// The executable, without quotes, environment variables unexpanded.
    pub exe: String,
    /// The argument string; empty when there are none.
    pub args: String,
    /// The command was generated by Purge rather than read from `QuietUninstallString`.
    pub generated: bool,
    /// The installer kind the command was built for.
    pub kind: InstallerKind,
}

impl QuietCommand {
    /// The command line: the executable quoted when it contains whitespace, then the arguments.
    pub fn to_command_line(&self) -> String {
        cmdline::SplitCommand {
            exe: self.exe.clone(),
            args: self.args.clone(),
        }
        .to_command_line()
    }

    /// The command with `%NAME%` references in the executable and the arguments expanded from `env`
    /// (names case-insensitive, unknown names left as written).
    pub fn expand(&self, env: &BTreeMap<String, String>) -> QuietCommand {
        let map: EnvMap = env.iter().map(|(k, v)| (k.as_str(), v.as_str())).collect();
        QuietCommand {
            exe: expand_with(&self.exe, &map),
            args: expand_with(&self.args, &map),
            ..self.clone()
        }
    }

    /// The argument string split at whitespace (quotes are not interpreted). For comparisons and display.
    pub fn arg_tokens(&self) -> Vec<&str> {
        self.args.split_whitespace().collect()
    }
}

/// Why an entry has no quiet command.
#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
pub enum QuietError {
    /// Neither `QuietUninstallString` nor `UninstallString` is set (and, for MSI, no ProductCode is known).
    #[error("the entry has no uninstall command")]
    NoUninstallString,
    /// An MSI entry whose ProductCode is unknown.
    #[error("the MSI entry has no ProductCode")]
    NoProductCode,
    /// The uninstall command could not be split into executable and arguments.
    #[error("the uninstall command cannot be split: {0}")]
    Unsplittable(#[from] CmdlineError),
    /// The installer kind has no known quiet form and the key gives none.
    #[error("no quiet uninstall form is known for installer kind {0:?}")]
    NoQuietForm(InstallerKind),
}

fn non_empty(s: Option<&str>) -> Option<&str> {
    s.filter(|s| !s.trim().is_empty())
}

/// Appends each switch of `add` that `args` does not already hold (compared with `same`).
fn with_switches(args: &str, add: &[&str], same: impl Fn(&str, &str) -> bool) -> String {
    let mut tokens: Vec<String> = args.split_whitespace().map(String::from).collect();
    for sw in add {
        if !tokens.iter().any(|t| same(t, sw)) {
            tokens.push((*sw).to_owned());
        }
    }
    tokens.join(" ")
}

/// The Inno form: the uninstaller's own arguments without `/SILENT`, plus [`INNO_QUIET_SWITCHES`].
fn inno_args(args: &str) -> String {
    let kept: Vec<&str> = args
        .split_whitespace()
        .filter(|t| !t.eq_ignore_ascii_case("/SILENT"))
        .collect();
    with_switches(&kept.join(" "), &INNO_QUIET_SWITCHES, |a, b| {
        a.eq_ignore_ascii_case(b)
    })
}

/// The NSIS form: `/S` added before a trailing `_?=<dir>`, which must stay last.
fn nsis_args(args: &str) -> String {
    let (head, tail) = match nsis_instdir_pos(args) {
        Some(i) => (args[..i].trim(), args[i..].trim()),
        None => (args.trim(), ""),
    };
    let head = with_switches(head, &[NSIS_QUIET_SWITCH], |a, b| a == b);
    [head.as_str(), tail]
        .iter()
        .filter(|s| !s.is_empty())
        .copied()
        .collect::<Vec<_>>()
        .join(" ")
}

/// Whether an Inno entry's `QuietUninstallString` is only Inno's own default: the same uninstaller with
/// nothing but [`INNO_SILENCE_SWITCHES`].
fn is_inno_default_quiet(quiet: &str, uninstall: Option<&str>) -> bool {
    let (Some(q), Some(u)) = (uninstaller(quiet), uninstall.and_then(uninstaller)) else {
        return false;
    };
    q.exe.eq_ignore_ascii_case(&u.exe)
        && q.args.split_whitespace().all(|t| {
            INNO_SILENCE_SWITCHES
                .iter()
                .any(|s| t.eq_ignore_ascii_case(s))
        })
}

/// The quiet uninstall command of `entry` (see the module documentation for the rules).
pub fn quiet_command(entry: &InventoryEntry) -> Result<QuietCommand, QuietError> {
    let kind = entry.installer_kind;
    let quiet = non_empty(entry.quiet_uninstall_string.as_deref());
    let uninstall = non_empty(entry.uninstall_string.as_deref());

    if let Some(q) = quiet
        && !(kind == InstallerKind::Inno && is_inno_default_quiet(q, uninstall))
    {
        let split = cmdline::split(q)?;
        return Ok(QuietCommand {
            exe: split.exe,
            args: split.args,
            generated: false,
            kind,
        });
    }
    generate(entry)
}

/// The generated quiet command of `entry`, ignoring any `QuietUninstallString` (rule 2).
pub fn generate(entry: &InventoryEntry) -> Result<QuietCommand, QuietError> {
    let kind = entry.installer_kind;
    let built = |exe: String, args: String| QuietCommand {
        exe,
        args,
        generated: true,
        kind,
    };
    if kind == InstallerKind::Msi {
        let code = entry
            .product_code
            .clone()
            .or_else(|| {
                non_empty(entry.uninstall_string.as_deref())
                    .and_then(crate::kind::msiexec_product_code)
            })
            .ok_or(QuietError::NoProductCode)?;
        return Ok(built(
            MSIEXEC.to_owned(),
            format!("/x {} {MSI_QUIET_ARGS}", code.to_ascii_uppercase()),
        ));
    }
    let uninstall =
        non_empty(entry.uninstall_string.as_deref()).ok_or(QuietError::NoUninstallString)?;
    let split = cmdline::split(uninstall)?;
    let args = match kind {
        InstallerKind::Inno => inno_args(&split.args),
        InstallerKind::Nsis => nsis_args(&split.args),
        InstallerKind::Burn => with_switches(&split.args, &BURN_QUIET_SWITCHES, |a, b| {
            a.eq_ignore_ascii_case(b)
        }),
        InstallerKind::Msi | InstallerKind::Unknown => return Err(QuietError::NoQuietForm(kind)),
    };
    Ok(built(split.exe, args))
}

