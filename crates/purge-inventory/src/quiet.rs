    #[test]
    fn quiet_errors() {
        use InstallerKind::*;
        let err = |kind, us: Option<&str>, qs: Option<&str>, pc: Option<&str>| {
            quiet_command(&entry("K", kind, us, qs, pc)).unwrap_err()
        };
        assert_eq!(
            err(Msi, Some("MsiExec.exe /X C:\\a.msi"), None, None),
            QuietError::NoProductCode
        );
        assert_eq!(err(Inno, None, None, None), QuietError::NoUninstallString);
        assert_eq!(
            err(Nsis, Some("   "), Some(""), None),
            QuietError::NoUninstallString
        );
        assert_eq!(
            err(Unknown, Some("x.exe"), None, None),
            QuietError::NoQuietForm(Unknown)
        );
        assert_eq!(
            err(Nsis, Some("\"C:\\unterminated.exe"), None, None),
            QuietError::Unsplittable(CmdlineError::UnterminatedQuote)
        );
    }

    #[test]
    fn expansion_and_command_line() {
        let e = entry("K", InstallerKind::Msi, None, None, Some(PC));
        let q = quiet_command(&e).unwrap();
        let env = BTreeMap::from([("SYSTEMROOT".to_owned(), r"C:\Windows".to_owned())]);
        let x = q.expand(&env);
        assert_eq!(x.exe, r"C:\Windows\System32\msiexec.exe");
        assert_eq!(x.args, q.args);
        assert_eq!(
            x.to_command_line(),
            r"C:\Windows\System32\msiexec.exe /x {23170F69-40C1-2702-2408-000001000000} /qn REBOOT=ReallySuppress"
        );
        let n = quiet_command(&entry(
            "K",
            InstallerKind::Nsis,
            Some(r#""C:\A B\u.exe""#),
            None,
            None,
        ))
        .unwrap();
        assert_eq!(n.to_command_line(), r#""C:\A B\u.exe" /S"#);
        assert_eq!(n.arg_tokens(), vec!["/S"]);
        let json = serde_json::to_string(&n).unwrap();
        assert_eq!(serde_json::from_str::<QuietCommand>(&json).unwrap(), n);
    }
